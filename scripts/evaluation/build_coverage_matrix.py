"""Build the EVAL-001 coverage matrix from the blueprints (so counts can never drift by hand).

Reads data/evaluation/questions/blueprint.yaml and corpus/manifest.json.
Writes data/evaluation/questions/coverage-matrix.yaml. Deterministic output.
Run: .venv/Scripts/python.exe scripts/evaluation/build_coverage_matrix.py
"""
import json
from collections import Counter
from pathlib import Path

import yaml

PROJECT_ROOT = Path(__file__).resolve().parents[2]
BLUEPRINTS = PROJECT_ROOT / "data" / "evaluation" / "questions" / "blueprint.yaml"
MATRIX = PROJECT_ROOT / "data" / "evaluation" / "questions" / "coverage-matrix.yaml"
MANIFEST = PROJECT_ROOT / "corpus" / "manifest.json"
HEADER = (
    "# GENERATED by scripts/evaluation/build_coverage_matrix.py from blueprint.yaml. Do not edit by hand.\n"
    "# Explanation of every dimension and of the gaps: docs/specs/evaluation-dataset-design.md\n"
)


def _counts(values):
    return dict(sorted(Counter(values).items()))


def _cross(cases, row, column):
    return {key: _counts(c[column] for c in cases if c[row] == key) for key in sorted({c[row] for c in cases})}


def _share(part, whole):
    return round(part / whole, 3) if whole else 0.0


def _by_source(cases, accepted):
    table = {}
    for source_id in accepted:
        expected = [c["id"] for c in cases if source_id in {s["source_id"] for s in c["expected_sources"]}]
        alternate = [c["id"] for c in cases
                     if source_id in {s["source_id"] for s in c["acceptable_alternate_sources"]}]
        near_miss = [c["id"] for c in cases if source_id in c.get("near_miss_sources", [])]
        languages = _counts(c["language"] for c in cases
                            if source_id in {s["source_id"] for s in c["expected_sources"]})
        table[source_id] = {"expected": expected, "alternate": alternate, "near_miss": near_miss,
                            "expected_by_language": languages}
    return table


def _dominance(cases):
    answerable = [c for c in cases if c["scope"] != "corpus-insufficient"]
    per_source = Counter(s for c in answerable for s in {x["source_id"] for x in c["expected_sources"]})
    top_source, top_count = max(sorted(per_source.items()), key=lambda item: item[1])
    huge = [c for c in answerable if c["size_class"] == "huge"]
    direct = [c for c in answerable if "direct_semantic" in c["retrieval_challenges"]]
    return {
        "answerable_cases": len(answerable),
        "most_used_source": {"source_id": top_source, "cases": top_count,
                             "share": _share(top_count, len(answerable))},
        "share_en": _share(sum(c["language"] == "en" for c in cases), len(cases)),
        "share_recall": _share(sum(c["cognitive_level"] == "recall" for c in cases), len(cases)),
        "share_easy": _share(sum(c["difficulty"] == "easy" for c in cases), len(cases)),
        "share_huge_documents": _share(len(huge), len(answerable)),
        "share_direct_semantic": _share(len(direct), len(answerable)),
    }


def build_matrix(blueprints):
    accepted = [d["source_id"] for d in json.loads(MANIFEST.read_text(encoding="utf-8"))["documents"]]
    cases = [b for b in blueprints if b["split"] == "eval"]
    dev = [b for b in blueprints if b["split"] == "dev"]
    groups = sorted({c["parallel_group_id"] for c in cases if c["parallel_group_id"]})
    by_source = _by_source(cases, accepted)
    return {
        "eval": {
            "total": len(cases),
            "by_scope": _counts(c["scope"] for c in cases),
            "by_language": _counts(c["language"] for c in cases),
            "by_cognitive_level": _counts(c["cognitive_level"] for c in cases),
            "by_difficulty": _counts(c["difficulty"] for c in cases),
            "by_size_class": _counts(c["size_class"] for c in cases),
            "by_failure_mode": _counts(c["evaluation_target"]["failure_mode"] for c in cases),
            "by_retrieval_challenge": _counts(t for c in cases for t in c["retrieval_challenges"]),
            "parallel": {
                "groups": len(groups),
                "cases_in_groups": sum(1 for c in cases if c["parallel_group_id"]),
                "cases_not_in_groups": sum(1 for c in cases if not c["parallel_group_id"]),
                "groups_by_difficulty": _counts(c["difficulty"] for c in cases
                                                if c["parallel_group_id"] and c["language"] == "en"),
                "groups_by_size_class": _counts(c["size_class"] for c in cases
                                                if c["parallel_group_id"] and c["language"] == "en"),
            },
            "language_x_scope": _cross(cases, "language", "scope"),
            "language_x_difficulty": _cross(cases, "language", "difficulty"),
            "language_x_cognitive_level": _cross(cases, "language", "cognitive_level"),
            "difficulty_x_cognitive_level": _cross(cases, "difficulty", "cognitive_level"),
            "by_source": by_source,
            "sources_without_expected_case": [s for s, row in by_source.items() if not row["expected"]],
            "dominance_checks": _dominance(cases),
        },
        "dev": {
            "total": len(dev),
            "by_language": _counts(c["language"] for c in dev),
            "by_scope": _counts(c["scope"] for c in dev),
        },
    }


def main():
    blueprints = yaml.safe_load(BLUEPRINTS.read_text(encoding="utf-8"))["blueprints"]
    body = yaml.safe_dump(build_matrix(blueprints), sort_keys=False, allow_unicode=True, width=100)
    MATRIX.write_text(HEADER + body, encoding="utf-8", newline="\n")
    print(f"wrote {MATRIX.relative_to(PROJECT_ROOT).as_posix()}")


if __name__ == "__main__":
    main()
